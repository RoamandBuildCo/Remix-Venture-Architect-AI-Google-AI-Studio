export async function exportInventoryToGoogleSheet(
  items: AppraisalDossier[],
  customTitle?: string
): Promise<SpreadsheetExportResult> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Google authentication required. Please sign in with Google to export to Sheets.');
  }

  const title = customTitle || `ShutterBuck Inventory Ledger (${new Date().toLocaleDateString()})`;

  // 1. Create a new Spreadsheet
  const createRes = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      properties: {
        title,
      },
      sheets: [
        {
          properties: {
            title: 'Inventory & Valuation',
            gridProperties: {
              frozenRowCount: 1,
            },
          },
        },
      ],
    }),
  });

  if (!createRes.ok) {
    const err = await createRes.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to create Google Spreadsheet');
  }

  const spreadsheetData = await createRes.json();
  const spreadsheetId = spreadsheetData.spreadsheetId;
  const spreadsheetUrl = `https://docs.google.com/spreadsheets/d/${spreadsheetId}/edit`;

  // 2. Prepare headers and rows
  const headers = [
    'Asset Name',
    'Category',
    'Status',
    'Fast Cash Price ($)',
    'Max Yield Price ($)',
    'Est. Fees & Ship ($)',
    'Net In-Pocket ($)',
    'Walk-Away Floor ($)',
    'Sell-Through (%)',
    'Days to Sell',
    'Serial / VIN Stamp',
    'Condition Tier',
    'Recommended Route',
    'Single Immediate Action',
    'Date Logged',
    'Dispute-Proof Title',
  ];

  const rows = items.map((i) => [
    i.assetName,
    i.category.toUpperCase(),
    i.status.toUpperCase(),
    i.financials.fastCashPrice,
    i.financials.maxYieldPrice,
    i.financials.estimatedFeesAndShipping,
    i.financials.netInPocketYield,
    i.financials.bottomDollarWalkAwayPrice,
    i.financials.sellThroughRatePercent,
    i.financials.medianDaysToSell,
    i.identification.detectedSerialOrTags || 'UNVERIFIED',
    i.conditionReport.conditionTier,
    i.financials.recommendedRoute,
    i.singleImmediateAction,
    i.dateLogged,
    i.turnkeyListing.title,
  ]);

  // Compute summary metrics
  const totalFastCash = items.reduce((acc, curr) => acc + (curr.financials.fastCashPrice || 0), 0);
  const totalNetYield = items.reduce((acc, curr) => acc + (curr.financials.netInPocketYield || 0), 0);
  const summaryRow = [
    'TOTALS / AVERAGES',
    `${items.length} ITEMS`,
    '',
    totalFastCash,
    '',
    '',
    totalNetYield,
    '',
    '',
    '',
    '',
    '',
    '',
    'Generated by ShutterBuck Engine',
    new Date().toISOString(),
    '',
  ];

  const allValues = [headers, ...rows, summaryRow];

  // 3. Write data to sheet
  const updateRes = await fetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values/Inventory%20%26%20Valuation!A1?valueInputOption=USER_ENTERED`,
    {
      method: 'PUT',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        values: allValues,
      }),
    }
  );

  if (!updateRes.ok) {
    const err = await updateRes.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to populate Google Sheet data');
  }

  return {
    spreadsheetId,
    spreadsheetUrl,
    title,
    rowCount: items.length,
  };
}

export async function exportVaultToGoogleSheet(
  items: AppraisalDossier[]
): Promise<SpreadsheetExportResult> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Google authentication required. Please sign in with Google to export to Sheets.');
  }

  const title = `ShutterBuck Fortress Vault Capital Allocation (${new Date().toLocaleDateString()})`;

  // Total cash calculations
  const totalRealizedCash = items
    .filter((i) => i.status === 'sold' && i.realizedSalePrice)
    .reduce((acc, curr) => acc + (curr.realizedSalePrice || 0), 0);

  const totalUnsoldFastCash = items
    .filter((i) => i.status !== 'sold' && i.status !== 'archived')
    .reduce((acc, curr) => acc + (curr.financials.fastCashPrice || 0), 0);

  const familySafetyVault = totalRealizedCash * 0.5;
  const workingArbitrageFund = totalRealizedCash * 0.4;
  const operatorSurvival = totalRealizedCash * 0.1;

  const createRes = await fetch('https://sheets.googleapis.com/v4/spreadsheets', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      properties: { title },
      sheets: [{ properties: { title: 'Fortress Split Allocation' } }],
    }),
  });

  if (!createRes.ok) {
    throw new Error('Failed to create Fortress Vault Spreadsheet');
  }

  const spreadsheetData = await createRes.json();
  const spreadsheetId = spreadsheetData.spreadsheetId;
  const spreadsheetUrl = `https://docs.google.com/spreadsheets/d/${spreadsheetId}/edit`;

  const values = [
    ['SHUTTERBUCK // FORTRESS VAULT 50/40/10 ALLOCATION'],
    ['Generated Date', new Date().toLocaleString()],
    ['Total Physical Cash Realized', totalRealizedCash],
    ['Total Unsold Inventory Liquidity', totalUnsoldFastCash],
    [],
    ['ALLOCATION PILLAR', 'PERCENTAGE', 'CAPITAL VALUE ($)', 'MANDATE & OPERATIONAL RULE'],
    ['Family Safety Vault', '50.0%', familySafetyVault, 'Untouchable cash reserve. Stored in physical envelope/high-yield FDIC lockbox. Minimum $1,000 threshold before any speculative reinvestment.'],
    ['Working Arbitrage Fund', '40.0%', workingArbitrageFund, 'Strict 2x multiplier rule. Deployed exclusively into immediate cash flips (e-bikes, scooters, high-demand tools).'],
    ['Operator Survival Draw', '10.0%', operatorSurvival, 'Groceries, essential living overhead, transit. Zero lifestyle creep.'],
    [],
    ['ACTIVE INVENTORY PIPELINE ASSETS'],
    ['Item Name', 'Category', 'Status', 'Fast Cash ($)', 'Immediate Action'],
    ...items.map((i) => [
      i.assetName,
      i.category,
      i.status,
      i.financials.fastCashPrice,
      i.singleImmediateAction,
    ]),
  ];

  await fetch(
    `https://sheets.googleapis.com/v4/spreadsheets/${spreadsheetId}/values/Fortress%20Split%20Allocation!A1?valueInputOption=USER_ENTERED`,
    {
      method: 'PUT',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ values }),
    }
  );

  return {
    spreadsheetId,
    spreadsheetUrl,
    title,
    rowCount: items.length + 8,
  };
}

