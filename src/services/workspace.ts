export async function getOrCreateVialeTaskList(): Promise<string> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Google authentication required. Please sign in with Google to use Tasks.');
  }

  // 1. List existing task lists
  const listRes = await fetch('https://tasks.googleapis.com/tasks/v1/users/@me/lists', {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (!listRes.ok) {
    throw new Error('Failed to retrieve Google Task lists');
  }

  const listData = await listRes.json();
  const lists: GoogleTaskList[] = listData.items || [];

  const existing = lists.find(
    (l) => l.title.includes('ShutterBuck') || l.title.includes('VIALE') || l.title.includes('LEV Operations')
  );

  if (existing) {
    return existing.id;
  }

  // 2. Create if not found
  const createRes = await fetch('https://tasks.googleapis.com/tasks/v1/users/@me/lists', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      title: '⚡ ShutterBuck Operations',
    }),
  });

  if (!createRes.ok) {
    throw new Error('Failed to create ShutterBuck Operations task list in Google Tasks');
  }

  const createdList = await createRes.json();
  return createdList.id;
}

export async function fetchGoogleTasks(taskListId?: string): Promise<GoogleTaskItem[]> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Google authentication required');
  }

  const targetListId = taskListId || (await getOrCreateVialeTaskList());
  const res = await fetch(`https://tasks.googleapis.com/tasks/v1/lists/${targetListId}/tasks?showCompleted=true&showHidden=true`, {
    headers: { Authorization: `Bearer ${token}` },
  });

  if (!res.ok) {
    throw new Error('Failed to fetch tasks from Google Tasks');
  }

  const data = await res.json();
  return (data.items || []).map((t: any) => ({
    id: t.id,
    title: t.title,
    notes: t.notes,
    status: t.status,
    due: t.due,
    completed: t.completed,
    updated: t.updated,
  }));
}

export async function createGoogleTask(
  title: string,
  notes?: string,
  due?: string,
  taskListId?: string
): Promise<GoogleTaskItem> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Google authentication required');
  }

  const targetListId = taskListId || (await getOrCreateVialeTaskList());

  const res = await fetch(`https://tasks.googleapis.com/tasks/v1/lists/${targetListId}/tasks`, {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${token}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      title,
      notes: notes || 'Dispatched from ShutterBuck Engine',
      due: due || undefined,
    }),
  });

  if (!res.ok) {
    const err = await res.json().catch(() => ({}));
    throw new Error(err.error?.message || 'Failed to create task in Google Tasks');
  }

  return await res.json();
}

export async function completeGoogleTask(
  taskId: string,
  taskListId?: string
): Promise<void> {
  const token = await getAccessToken();
  if (!token) {
    throw new Error('Google authentication required');
  }

  const targetListId = taskListId || (await getOrCreateVialeTaskList());

  const res = await fetch(
    `https://tasks.googleapis.com/tasks/v1/lists/${targetListId}/tasks/${taskId}`,
    {
      method: 'PATCH',
      headers: {
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        status: 'completed',
      }),
    }
  );

  if (!res.ok) {
    throw new Error('Failed to update task status in Google Tasks');
  }
}

export async function syncRoadmapStepsToGoogleTasks(
  steps: RoadmapStep[]
): Promise<{ added: number; taskListId: string }> {
  const taskListId = await getOrCreateVialeTaskList();
  const existingTasks = await fetchGoogleTasks(taskListId);
  const existingTitles = new Set(existingTasks.map((t) => t.title.toLowerCase().trim()));

  let added = 0;
  for (const step of steps) {
    const titleKey = `[${step.levelName.toUpperCase()}] ${step.title}`.toLowerCase().trim();
    if (!existingTitles.has(titleKey)) {
      const notes = `Phase: ${step.phase} (${step.timeframe})\nTarget: ${step.targetMetric}\nFailsafe: ${step.failSafeWarning}\nVerification: ${step.verificationTrigger}`;
      await createGoogleTask(`[${step.levelName.toUpperCase()}] ${step.title}`, notes, undefined, taskListId);
      added++;
    }
  }

  return { added, taskListId };
}
